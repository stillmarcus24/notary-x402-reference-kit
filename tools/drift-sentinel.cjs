#!/usr/bin/env node
'use strict';
/*
 * drift-sentinel.cjs — continuous truth check for every axis this package can drift on.
 *
 * Why this exists (2026-09-14). Every gate we had ran at PUBLISH time. Publishing is
 * exactly when someone is paying attention, which is the wrong time to find drift. The
 * three failures this closes all happened BETWEEN publishes:
 *
 *   - the published implementation fell behind the running service and the manifest's
 *     byte-identity claim went stale for two days (found by re-sealing, by luck of
 *     doing unrelated work);
 *   - a retired bond wallet sat in the README for 34 hours after a reviewer named it
 *     in public;
 *   - the same unqualified payout claim survived in three more surfaces, one of them
 *     machine-readable and served to counterparties.
 *
 * A claim is not true because it was true when we shipped it. Four axes, because we
 * have now been bitten on four:
 *
 *   A1 INTERNAL   manifest <-> every human/machine surface   (check-consistency.cjs)
 *   A2 RUNTIME    published implementation <-> running code  (the byte-identity claim)
 *   A3 PUBLISHED  local working tree <-> GitHub main         (check-published-sync.cjs)
 *   A4 LIVE       published claims <-> what the live service actually serves
 *
 * A4 is the one no file-level check can reach: the kit's live-bond-status.json is a
 * SNAPSHOT, while /notary/bond is generated by the running service. Those are two
 * different writers and they have disagreed before.
 *
 *   node tools/drift-sentinel.cjs          # exit 0 clean, 1 drift, 2 harness error
 *   node tools/drift-sentinel.cjs --quiet  # print only on drift (cron mode)
 */
const fs = require('fs');
const path = require('path');
const https = require('https');
const { execFileSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const QUIET = process.argv.includes('--quiet');
const findings = [];
const lines = [];
const say = (s) => { lines.push(s); };

const m = JSON.parse(fs.readFileSync(path.join(ROOT, 'manifest/manifest.json'), 'utf8'));

function runGate(name, file, args = []) {
  try {
    execFileSync('node', [path.join(ROOT, file), ...args], { cwd: ROOT, stdio: 'pipe' });
    say(`  OK    ${name}`);
    return true;
  } catch (e) {
    const out = ((e.stdout || '') + (e.stderr || '')).toString();
    const fail = out.split('\n').filter(l => /FAIL|DRIFT|MISMATCH|differs/i.test(l)).slice(0, 6);
    say(`  DRIFT ${name}`);
    fail.forEach(l => say(`          ${l.trim()}`));
    findings.push({ axis: name, detail: fail.join(' | ') || out.slice(-300) });
    return false;
  }
}

function get(url) {
  return new Promise((resolve, reject) => {
    https.get(url, { headers: { 'User-Agent': 'stillos-drift-sentinel' }, timeout: 20000 }, res => {
      if (res.statusCode !== 200) { res.resume(); return reject(new Error(`HTTP ${res.statusCode}`)); }
      let b = ''; res.on('data', d => b += d);
      res.on('end', () => { try { resolve(JSON.parse(b)); } catch (err) { reject(err); } });
    }).on('error', reject).on('timeout', function () { this.destroy(); reject(new Error('timeout')); });
  });
}

(async () => {
  say(`\ndrift sentinel — ${new Date().toISOString()}\n`);

  // --- A1 INTERNAL -------------------------------------------------------------
  runGate('A1 internal   manifest <-> surfaces', 'tools/check-consistency.cjs');

  // --- A2 RUNTIME --------------------------------------------------------------
  // seal-manifest RECOMPUTES published_matches_running rather than trusting the
  // stored string. Compare each published bond file to the code actually running.
  const src = m.parties.stillos.implementation_source_dir || '/home/marcus/core';
  const bondDir = path.join(ROOT, 'implementation/bond');
  const diverged = [];
  for (const f of fs.readdirSync(bondDir).filter(f => f.endsWith('.cjs'))) {
    const live = path.join(src, f);
    if (!fs.existsSync(live)) { diverged.push(`${f}: NOT PRESENT in ${src}`); continue; }
    if (!fs.readFileSync(path.join(bondDir, f)).equals(fs.readFileSync(live))) {
      diverged.push(`${f}: DIFFERS from running`);
    }
  }
  const claim = m.parties.stillos.deployment_status.published_matches_running;
  const claimsYes = /^YES/.test(claim);
  if (diverged.length) {
    say('  DRIFT A2 runtime    published <-> running');
    diverged.forEach(d => say(`          ${d}`));
    findings.push({ axis: 'A2 runtime', detail: diverged.join(' | ') });
  } else if (!claimsYes) {
    say('  DRIFT A2 runtime    files match but manifest still claims otherwise');
    findings.push({ axis: 'A2 runtime', detail: `stale claim: ${claim}` });
  } else {
    say('  OK    A2 runtime    published <-> running');
  }

  // --- A3 PUBLISHED ------------------------------------------------------------
  runGate('A3 published  working tree <-> GitHub main', 'tools/check-published-sync.cjs');

  // --- A4 LIVE -----------------------------------------------------------------
  // The kit's live-bond-status.json is a snapshot; /notary/bond is generated by the
  // running service. Two writers, two chances to be wrong. Assert the facts a
  // counterparty acts on, and assert the payout language is qualified AT THE SOURCE.
  try {
    const bond = await get('https://stillosdigitalholdings.com/notary/bond');
    const bad = [];
    if (String(bond.wallet).toLowerCase() !== m.bond.wallet.toLowerCase())
      bad.push(`live wallet ${bond.wallet} != manifest ${m.bond.wallet}`);
    if (bond.custody_type !== m.custody.type)
      bad.push(`live custody ${bond.custody_type} != manifest ${m.custody.type}`);
    if (bond.collateral_funded === false && m.bond.active === true)
      bad.push('live reports collateral NOT funded while manifest claims active');

    const PAYS = /pays? out\b|is paid\b|paid up to|disputant is paid/i;
    const QUAL = /2-of-2|2of2|second (human )?signature|two human signatures|multisig|not instant|no committed payout SLA|governed execution|requires a human/i;
    for (const [k, v] of Object.entries(bond)) {
      if (typeof v === 'string' && PAYS.test(v) && !QUAL.test(v))
        bad.push(`live /notary/bond field '${k}' promises payout with no custody qualifier`);
    }
    if (bad.length) {
      say('  DRIFT A4 live       service <-> published claims');
      bad.forEach(b => say(`          ${b}`));
      findings.push({ axis: 'A4 live', detail: bad.join(' | ') });
    } else {
      say('  OK    A4 live       service <-> published claims');
    }
  } catch (e) {
    // An unreachable service is NOT a refutation — same rule as rec-13 and the
    // offline verifier's unknown-schema handling. Report it as unknown, not as drift.
    say(`  UNKNOWN A4 live     could not reach /notary/bond (${e.message}) — not counted as drift`);
  }

  say(`\n  ${findings.length === 0 ? 'NO DRIFT' : findings.length + ' DRIFT FINDING(S)'}\n`);

  const state = path.join(ROOT, 'state-drift-sentinel.json');
  fs.writeFileSync(state, JSON.stringify(
    { checked_at: new Date().toISOString(), clean: findings.length === 0, findings }, null, 2) + '\n');

  if (!QUIET || findings.length) console.log(lines.join('\n'));

  if (findings.length) {
    try {
      execFileSync('node', [path.join('/home/marcus/core', 'notify.cjs'),
        `DRIFT: notary reference kit — ${findings.map(f => f.axis).join(', ')}`,
        findings.map(f => `${f.axis}: ${f.detail}`).join('\n')], { stdio: 'pipe', timeout: 30000 });
    } catch (_) { /* alerting must never mask the finding; exit code carries it */ }
  }
  process.exit(findings.length ? 1 : 0);
})().catch(e => { console.error('sentinel harness error:', e.message); process.exit(2); });
